#!/usr/bin/env python3
"""Builds Resources/<lang>.lproj/{Localizable,InfoPlist}.strings from translations/<lang>.json (English is the source)."""
import glob, json, os

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

INFO = {"NSFaceIDUsageDescription": "LionCar asks for Face ID before it unlocks your car or sounds its horn."}
INFO_EL = {"NSFaceIDUsageDescription": "Το LionCar ζητά Face ID πριν ξεκλειδώσει το αυτοκίνητό σας ή πατήσει την κόρνα."}
INFO_NL = {"NSFaceIDUsageDescription": "LionCar vraagt om Face ID voordat het je auto ontgrendelt of de claxon laat klinken."}

os.makedirs("Resources/en.lproj", exist_ok=True)
open("Resources/en.lproj/Localizable.strings", "w").write("/* English is the development language: keys are the English texts. */\n")
open("Resources/en.lproj/InfoPlist.strings", "w").write("".join(f'"{k}" = "{esc(v)}";\n' for k, v in INFO.items()))
for path in sorted(glob.glob("translations/*.json")):
    lang = os.path.splitext(os.path.basename(path))[0]
    t = json.load(open(path))
    os.makedirs(f"Resources/{lang}.lproj", exist_ok=True)
    with open(f"Resources/{lang}.lproj/Localizable.strings", "w") as f:
        f.write(f"/* Generated by scripts/make_strings.py from {path}. Edit the JSON, not this file. */\n")
        for k, v in sorted(t.items()):
            f.write(f'"{esc(k)}" = "{esc(v)}";\n')
    info = {"el": INFO_EL, "nl": INFO_NL}.get(lang)
    if info:
        open(f"Resources/{lang}.lproj/InfoPlist.strings", "w").write("".join(f'"{k}" = "{esc(v)}";\n' for k, v in info.items()))
    print(lang, len(t))
