#!/usr/bin/env python3
"""Regenerates Core/Sources/LionCore/StellantisConfigsData.swift from LionFlow's stellantis_configs.json."""
import json, sys
src, dst = sys.argv[1], sys.argv[2]
data = json.dumps(json.load(open(src)), separators=(",", ":"), ensure_ascii=False)
assert '"""#' not in data
open(dst, "w").write("// Generated by scripts/embed_configs.py from LionFlow's stellantis_configs.json. Do not edit.\n"
                     "let stellantisConfigsJSON = #\"\"\"\n" + data + "\n\"\"\"#\n")
